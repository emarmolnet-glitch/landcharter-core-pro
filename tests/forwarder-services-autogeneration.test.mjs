test('1. ForwarderWorkspace persistProjectToDatabase contains services autogeneration logic', () => {
  // Check persistProjectToDatabase exists
  const persistMatch = forwarderWorkspaceSource.match(
    /const\s+persistProjectToDatabase\s*=\s*async\s*\([^)]*\)\s*=>\s*\{([\s\S]*?)(?:const\s+handleSaveProject|\n\s*return\s+finalSaved;)/
  );
  assert.ok(persistMatch, 'persistProjectToDatabase definition must exist in ForwarderWorkspace.jsx');
  const persistBody = persistMatch[1];

  // 1. Checks servicesList.length === 0 and land freight cost > 0
  assert.match(
    persistBody,
    /servicesList\.length\s*===\s*0\s*&&[\s\S]*?(?:tuVariableDeCosteTotalTerrestre|costeCalculado)/,
    'Must check if servicesList is empty and positive land cost exists'
  );

  // 2. Generates service with srv-auto- id and Flete y Operaciones Terrestres name
  assert.match(
    persistBody,
    /id:\s*['"]srv-auto-['"]\s*\+\s*Date\.now\(\)/,
    'Must generate service id starting with srv-auto- and timestamp'
  );

  assert.match(
    persistBody,
    /name:\s*autoServiceName|name:\s*finalAutoName|name:\s*['"]Flete y Operaciones Terrestres \(['"]/,
    'Must assign service name matching Flete y Operaciones Terrestres format'
  );

  // 3. Sets cost and sale
  assert.match(
    persistBody,
    /cost:\s*(?:costeCalculado|finalAutoCost|calculatedLandCost)/,
    'Must set cost on auto-generated service'
  );
  assert.match(
    persistBody,
    /sale:\s*(?:ventaCalculada|finalAutoSale|calculatedLandSale)/,
    'Must set sale on auto-generated service'
  );

  // 4. Injects service into payload
  assert.match(
    persistBody,
    /services:\s*servicesList/,
    'Payload must bind servicesList'
  );
});

