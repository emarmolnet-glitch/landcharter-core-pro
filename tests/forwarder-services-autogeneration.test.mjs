test('3. Behavioral simulation: Autogenerates default service when servicesList is empty and cost > 0', () => {
  // Simulate the exact logic from persistProjectToDatabase
  const projectToSave = {
    project_ref: 'EXP-123456',
    land_origin: 'Madrid',
    land_destination: 'Valencia',
    land_distance: 350,
    total_trucks: 2,
    land_freight_cost: 1100,
    land_freight_sale: 1300,
    services: [],
    line_items: [],
  };

  const servicesList = (Array.isArray(projectToSave?.services) && projectToSave.services.length > 0)
    ? [...projectToSave.services]
    : (Array.isArray(projectToSave?.line_items) && projectToSave.line_items.length > 0 ? [...projectToSave.line_items] : []);

  const distanceKm = Number(projectToSave.land_distance);
  const tuVariableDeCosteTotalTerrestre = 1100;
  const tuVariableDePrecioVentaTerrestre = 1300;
  const costeCalculado = Number(projectToSave?.land_freight_cost) || tuVariableDeCosteTotalTerrestre;
  const ventaCalculada = Number(projectToSave?.land_freight_sale) || tuVariableDePrecioVentaTerrestre;
  const autoTotalTrucks = Number(projectToSave?.total_trucks) || 1;
  const autoLandOrigin = projectToSave?.land_origin || 'Origen';
  const autoLandDestination = projectToSave?.land_destination || 'Destino';

  if (servicesList.length === 0 && !projectToSave?.is_delete_action && (Number(tuVariableDeCosteTotalTerrestre) > 0 || costeCalculado > 0)) {
    const autoServiceName = 'Flete y Operaciones Terrestres (' + (autoTotalTrucks || 1) + ' Camiones: ' + (autoLandOrigin || 'Origen') + ' ➔ ' + (autoLandDestination || 'Destino') + ')';
    const defaultService = {
      id: 'srv-auto-' + Date.now(),
      name: autoServiceName,
      description: autoServiceName,
      cost: costeCalculado,
      sale: ventaCalculada,
      cost_eur: costeCalculado,
      sale_price_eur: ventaCalculada,
      margin_eur: Number((ventaCalculada - costeCalculado).toFixed(2)),
      land_freight_cost: costeCalculado,
      land_freight_sale: ventaCalculada,
    };
    servicesList.push(defaultService);
  }

  assert.equal(servicesList.length, 1, 'servicesList should have 1 auto-generated service');
  assert.match(servicesList[0].id, /^srv-auto-\d+$/);
  assert.equal(servicesList[0].name, 'Flete y Operaciones Terrestres (2 Camiones: Madrid ➔ Valencia)');
  assert.equal(servicesList[0].cost, 1100);
  assert.equal(servicesList[0].sale, 1300);
  assert.equal(servicesList[0].cost_eur, 1100);
  assert.equal(servicesList[0].sale_price_eur, 1300);
});

